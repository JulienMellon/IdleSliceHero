/// <reference types="node" />
// Writes docs/API.md: one line per export of the engine and the content tables, so a programmer can find a signature
// without opening game.ts. No bodies. Run it after changing an export:  npx tsx scripts/api-digest.ts
//
//   src/engine/**               name(signature) — file:line — first JSDoc sentence
//   src/content/types.ts        same
//   src/content/tuning.ts, hooks.ts   names only (one line each)
//   src/components/pulse-bus.ts, coin-layer.tsx, slots.tsx   same as the engine, when present
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

/** Run from the repo root (npm scripts and the card both do). */
const ROOT = process.cwd();
const OUT = path.join(ROOT, 'docs', 'API.md');
const MAX_SIG = 110;
const MAX_DOC = 100;

const HEADER = `# Engine API digest (generated by \`npx tsx scripts/api-digest.ts\`; do not edit by hand)

## How to add a feature
1. New file \`src/engine/features/<name>.ts\` exporting a \`Feature<S>\` (features/types.ts): \`key\`, \`init(now)\`, \`migrate(raw, now)\` (raw may be undefined: old saves).
2. Optional hooks: \`tick(g, dtPlay, now)\`, \`shopValueMult(g, id, now)\`, \`shopDemandMult(g, id, now)\`, \`onOffline(g, seconds, now)\`.
3. Add it to \`FEATURES\` in features/index.ts: one line. Hooks run in that order, after the ordinary tick / offline body. game.ts is not edited.
4. Its state lives at \`GameState.x[key]\` and is saved with the game (SAVE_VERSION stays 5). Read: \`getFeature(g, f)\`; write: \`setFeature(g, f, s)\`.
5. Multipliers reach the UI through \`shopEarnings(g, id)\`; the pure rate helpers take an optional \`FeatureMults\` (\`featureMults(g, id)\`).
6. Test with \`withFeatures([f], () => ...)\` (features.test.ts shows every hook); golden.test.ts must still pass with none registered.
7. UI plugs in through the slots (HUD chips, banners, sheets, drawer cards, scene overlays): see src/components/slots.tsx.
8. Story scenes: one file per neighbourhood in src/content/scenes/home/, joined in home/index.ts; scenes-golden.test.ts pins ids and text.
9. Types are listed by name only (one "types:" line per file); everything else is name(signature) — file:line — first doc sentence.
10. Not listed: src/components/** other than the three files at the end, src/store/**, src/audio/**.
`;

/** Files to digest, in order. `names` = list the exported names only. */
const SOURCES: { match: (rel: string) => boolean; names?: boolean }[] = [
  { match: (r) => r.startsWith('src/engine/') && !r.includes('__tests__') && /\.tsx?$/.test(r) },
  { match: (r) => r === 'src/content/types.ts' },
  { match: (r) => r === 'src/content/tuning.ts' || r === 'src/content/hooks.ts', names: true },
  { match: (r) => ['src/components/pulse-bus.ts', 'src/components/coin-layer.tsx', 'src/components/slots.tsx'].includes(r) },
];

function walk(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
}

const clip = (s: string, n: number) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);
const oneLine = (s: string) => s.replace(/\s+/g, ' ').trim();

function firstSentence(node: ts.Node): string {
  const doc = ts.getJSDocCommentsAndTags(node).find(ts.isJSDoc);
  if (!doc || !doc.comment) return '';
  const text = oneLine(typeof doc.comment === 'string' ? doc.comment : doc.comment.map((c) => c.text).join(''));
  const m = text.match(/^(.*?[.!?])(\s|$)/);
  return clip(m ? m[1] : text, MAX_DOC);
}

const isExported = (n: ts.Node) => !!(ts.canHaveModifiers(n) && ts.getModifiers(n)?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword));

function fnSig(name: string, fn: ts.SignatureDeclaration): string {
  const tps = fn.typeParameters ? `<${fn.typeParameters.map((t) => t.getText()).join(', ')}>` : '';
  const ps = fn.parameters.map((p) => oneLine(p.getText())).join(', ');
  const ret = fn.type ? `: ${oneLine(fn.type.getText())}` : '';
  return clip(`${name}${tps}(${ps})${ret}`, MAX_SIG);
}

interface Item {
  name: string;
  sig: string;
  line: number;
  doc: string;
}

function itemsOf(file: string): Item[] {
  const text = fs.readFileSync(file, 'utf8');
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, file.endsWith('x') ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const out: Item[] = [];
  const lineOf = (n: ts.Node) => sf.getLineAndCharacterOfPosition(n.getStart()).line + 1;
  for (const st of sf.statements) {
    if (ts.isFunctionDeclaration(st) && isExported(st) && st.name) {
      out.push({ name: st.name.text, sig: fnSig(st.name.text, st), line: lineOf(st), doc: firstSentence(st) });
    } else if (ts.isVariableStatement(st) && isExported(st)) {
      for (const d of st.declarationList.declarations) {
        if (!ts.isIdentifier(d.name)) continue;
        const name = d.name.text;
        const init = d.initializer;
        let sig = name;
        if (init && (ts.isArrowFunction(init) || ts.isFunctionExpression(init))) sig = fnSig(name, init);
        else if (d.type) sig = clip(`${name}: ${oneLine(d.type.getText())}`, MAX_SIG);
        out.push({ name, sig, line: lineOf(st), doc: firstSentence(st) });
      }
    } else if (ts.isInterfaceDeclaration(st) && isExported(st)) {
      out.push({ name: st.name.text, sig: `interface ${st.name.text}`, line: lineOf(st), doc: firstSentence(st) });
    } else if (ts.isTypeAliasDeclaration(st) && isExported(st)) {
      out.push({ name: st.name.text, sig: `type ${st.name.text}`, line: lineOf(st), doc: firstSentence(st) });
    } else if (ts.isClassDeclaration(st) && isExported(st) && st.name) {
      out.push({ name: st.name.text, sig: `class ${st.name.text}`, line: lineOf(st), doc: firstSentence(st) });
    } else if (ts.isEnumDeclaration(st) && isExported(st)) {
      out.push({ name: st.name.text, sig: `enum ${st.name.text}`, line: lineOf(st), doc: firstSentence(st) });
    } else if (ts.isExportDeclaration(st) && st.exportClause && ts.isNamedExports(st.exportClause)) {
      for (const e of st.exportClause.elements) out.push({ name: e.name.text, sig: `${e.name.text} (re-export)`, line: lineOf(st), doc: '' });
    }
  }
  return out;
}

function digest(): string {
  const files = walk(path.join(ROOT, 'src'))
    .map((f) => path.relative(ROOT, f).split(path.sep).join('/'))
    .sort();
  const lines: string[] = [HEADER.trimEnd()];
  for (const src of SOURCES) {
    for (const rel of files.filter(src.match)) {
      const items = itemsOf(path.join(ROOT, rel));
      if (!items.length) continue;
      lines.push('', `## ${rel}`);
      if (src.names) lines.push(items.map((i) => i.name).join(', '));
      else {
        const types = items.filter((i) => /^(interface|type) /.test(i.sig));
        for (const i of items) if (!types.includes(i)) lines.push(`- ${i.sig} — ${rel}:${i.line}${i.doc ? ` — ${i.doc}` : ''}`);
        if (types.length) lines.push(`- types: ${types.map((t) => t.name).join(', ')}`);
      }
    }
  }
  return `${lines.join('\n')}\n`;
}

const md = digest();
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, md);
console.log(`wrote ${path.relative(ROOT, OUT)} (${md.split('\n').length - 1} lines)`);
