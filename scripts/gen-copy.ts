/// <reference types="node" />
// Writes the GENERATED copy tables of the home city (src/content/copy/home/{endgame,layers,menu,shifts,stars}.ts) from the writer's copy files
// docs/story/COPY-v5.15.md and COPY-v5.16.md, so the .ts tables are never edited by hand. Run from the repo root after the copy file changes:
//   npx tsx scripts/gen-copy.ts
// The compare tests (components/**/copy tests) still read the copy files themselves and fail when a table and its file disagree.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const OUT = path.join(ROOT, 'src', 'content', 'copy', 'home');
const CMD = 'npx tsx scripts/gen-copy.ts';

/** One row of a copy file's table: `| \`key\` | … | text |`, as trimmed cells (the same split the compare tests use). */
type Cells = string[];
interface Section {
  /** The `## ` number ("1", "2"...). */
  n: string;
  /** The `### ` heading the row sits under ('' before the first). */
  sub: string;
  cells: Cells;
}

/** Every table row of a copy file, with the section number and `###` heading it sits under. */
function readRows(file: string): Section[] {
  const md = fs.readFileSync(path.join(ROOT, 'docs', 'story', file), 'utf8');
  const out: Section[] = [];
  for (const sec of md.split(/^## /m).slice(1)) {
    const [head, ...body] = sec.split('\n');
    const n = head.split('.')[0];
    let sub = '';
    for (const line of body) {
      if (line.startsWith('### ')) sub = line.slice(4).trim();
      if (!line.startsWith('| `')) continue;
      out.push({
        n,
        sub,
        cells: line
          .trim()
          .replace(/^\||\|$/g, '')
          .split(' | ')
          .map((c) => c.trim()),
      });
    }
  }
  return out;
}

const keyOf = (cells: Cells): string => cells[0].replace(/`/g, '');
const q = (s: string): string => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const entries = (rows: [string, string][]): string => rows.map(([k, v]) => `  ${q(k)}: ${q(v)},`).join('\n');

interface Table {
  copy: [string, string][];
  speakers: [string, string][];
  names: [string, string][];
}

/** Rows of 3 cells (key, speaker, text) into a table; the speaker "—" is none. */
function addSpeakerRow(t: Table, cells: Cells): void {
  t.copy.push([keyOf(cells), cells[2]]);
  if (cells[1] !== '—') t.speakers.push([keyOf(cells), cells[1]]);
}

function emit(opts: { file: string; header: string[]; copy: string; keyType: string; speakers: string; speakerDoc: string; names?: string; t: Table }): string {
  const { t } = opts;
  const parts = [
    opts.header.map((l) => `// ${l}`).join('\n'),
    '',
    `/** Every line, by its key in the copy file.${opts.names ? " Recipe keys hold the flavour line; the card's name is in RECIPE_NAMES." : ''} */`,
    `export const ${opts.copy} = {`,
    entries(t.copy),
    '} as const;',
    '',
    `export type ${opts.keyType} = keyof typeof ${opts.copy};`,
    '',
    `/** ${opts.speakerDoc} */`,
    `export const ${opts.speakers}: Readonly<Record<string, string>> = {`,
    entries(t.speakers),
    '};',
  ];
  if (opts.names)
    parts.push(
      '',
      "/** A recipe card's name, by `recipe.<hood>.<1-4>`. */",
      `export const ${opts.names}: Readonly<Record<string, string>> = {`,
      entries(t.names),
      '};',
    );
  return parts.join('\n') + '\n';
}

const SPEAKER_DOC = 'Who says a line (keys with a speaker in the copy file; the others have none).';

function build(): Record<string, { src: string }> {
  const v15 = readRows('COPY-v5.15.md');
  const v16 = readRows('COPY-v5.16.md');
  const out: Record<string, { src: string }> = {};

  // endgame: COPY-v5.15 sections 1, 3, 4, 5, 6, 7 (section 1 is key | name | line; 7 is key | text)
  {
    const t: Table = { copy: [], speakers: [], names: [] };
    for (const { n, cells } of v15) {
      if (!['1', '3', '4', '5', '6', '7'].includes(n)) continue;
      if (n === '1') {
        t.names.push([keyOf(cells), cells[1]]);
        t.copy.push([keyOf(cells), cells[2]]);
      } else if (cells.length === 3) addSpeakerRow(t, cells);
      else t.copy.push([keyOf(cells), cells[1]]);
    }
    out['endgame.ts'] = {
      src: emit({
        file: 'endgame.ts',
        header: [
          `GENERATED by \`${CMD}\` from docs/story/COPY-v5.15.md (sections 1, 3, 4, 5, 6, 7) by key. Do not edit by hand: change the copy file and regenerate.`,
          'copy.test.ts fails when this file and the copy file disagree. Barks (section 2) and the cameo (section 8) belong to card S1.',
        ],
        copy: 'COPY',
        keyType: 'CopyKey',
        speakers: 'SPEAKERS',
        speakerDoc: SPEAKER_DOC,
        names: 'RECIPE_NAMES',
        t,
      }),
    };
  }

  // layers: COPY-v5.16 section 1 (Suburbs, Waterfront) and section 2 (the rival)
  {
    const t: Table = { copy: [], speakers: [], names: [] };
    for (const { n, cells } of v16) {
      if (n !== '1' && n !== '2') continue;
      if (n === '1' && !/^(layer\.(suburbs|waterfront)|upgrade\.waterfront)/.test(keyOf(cells))) continue;
      if (cells.length === 3) addSpeakerRow(t, cells);
    }
    out['layers.ts'] = {
      src: emit({
        file: 'layers.ts',
        header: [
          `GENERATED by \`${CMD}\` from docs/story/COPY-v5.16.md (section 1: Suburbs, Waterfront; section 2: the rival) by key. Do not edit by hand: change the copy file and regenerate.`,
          'layer-copy.test.ts fails when this file and the copy file disagree. University, Industrial and Uptown (card S2b) keep their own table.',
        ],
        copy: 'LAYER_COPY',
        keyType: 'LayerCopyKey',
        speakers: 'LAYER_SPEAKERS',
        speakerDoc: SPEAKER_DOC,
        t,
      }),
    };
  }

  // menu, shifts, stars: COPY-v5.16 section 1, one table per neighbourhood's subsections
  for (const [file, hood, name] of [
    ['menu.ts', 'university', 'University'],
    ['shifts.ts', 'industrial', 'Industrial'],
    ['stars.ts', 'uptown', 'Uptown'],
  ] as const) {
    const t: Table = { copy: [], speakers: [], names: [] };
    for (const { n, sub, cells } of v16) if (n === '1' && sub.split(' · ')[0].toLowerCase() === hood) addSpeakerRow(t, cells);
    out[file] = {
      src: emit({
        file,
        header: [
          `GENERATED by \`${CMD}\` from docs/story/COPY-v5.16.md section 1 (${name} subsections) by key. Do not edit by hand: change the copy file and regenerate.`,
          'copy.test.ts fails when this file and the copy file disagree.',
        ],
        copy: 'COPY',
        keyType: 'CopyKey',
        speakers: 'SPEAKERS',
        speakerDoc: SPEAKER_DOC,
        t,
      }),
    };
  }
  return out;
}

async function main(): Promise<void> {
  const prettier = await import('prettier');
  fs.mkdirSync(OUT, { recursive: true });
  for (const [file, { src }] of Object.entries(build())) {
    const target = path.join(OUT, file);
    const config = (await prettier.resolveConfig(target)) ?? {};
    const text = await prettier.format(src, { ...config, parser: 'typescript' });
    fs.writeFileSync(target, text);
    console.log(`wrote ${path.relative(ROOT, target)}`);
  }
}

void main();
