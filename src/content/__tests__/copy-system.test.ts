/// <reference types="jest" />
// Card R5c: the one copy system. `fill` is the one placeholder filler, `t` looks in the city pack's `copy` first and then in the home tables, the
// generated tables are the copy files' rows (their own compare tests), and a pack never imports content/copy.
import * as fs from 'fs';
import * as path from 'path';

import { COPY as CHAPTERS } from '../copy/home/chapters';
import { COPY as ENDGAME } from '../copy/home/endgame';
import { LAYER_COPY } from '../copy/home/layers';
import { LINES } from '../copy/home/lines';
import { COPY as MENU } from '../copy/home/menu';
import { COPY as SHIFTS } from '../copy/home/shifts';
import { COPY as STARS } from '../copy/home/stars';
import { COPY as TUTORIAL } from '../copy/home/tutorial';
import { CITIES } from '../cities';
import { BOSTON_COPY } from '../cities/boston/copy';
import { dressed, fill, HOME_COPY, isDressed, t } from '../copy';

describe('fill', () => {
  test('replaces each {name}; a placeholder with no value is left as written', () => {
    expect(fill('Game Day {time}', { time: '3:07' })).toBe('Game Day 3:07');
    expect(fill('{a} and {b}', { a: 1 })).toBe('1 and {b}');
    expect(fill('no placeholders')).toBe('no placeholders');
  });
});

describe('t: the pack first, then home', () => {
  test('home: a home key says its home line, filled', () => {
    expect(t('layer.suburbs.gameday.chip', { time: '1:00' })).toBe('Game Day 1:00');
    expect(t('layer.suburbs.gameday.chip', { time: '1:00' }, 'home')).toBe('Game Day 1:00');
    expect(t('lot.pin.founder', { founder: 'Nonna', n: 60 })).toBe('Nonna in 60');
  });
  test('Boston: a key the pack overrides says the pack line; a key it does not says home', () => {
    expect(CITIES.boston.copy).toBe(BOSTON_COPY);
    expect(t('upgrade.waterfront.rack.tier.1', {}, 'boston')).toBe('Corner Shelf');
    expect(t('upgrade.waterfront.rack.tier.1')).toBe('Dinghy Rack');
    expect(t('layer.suburbs.gameday.chip.rush', { time: '2:00' }, 'boston')).toMatch(/2:00$/);
    expect(t('layer.suburbs.gameday.start', {}, 'boston')).toBe(LAYER_COPY['layer.suburbs.gameday.start']);
    expect(t('lot.pin.founder', { founder: 'Father Dom', n: 5 }, 'boston')).toBe('Father Dom in 5');
  });
  test('dressed and isDressed are the same lookup', () => {
    expect(isDressed('boston', 'upgrade.waterfront.rack.tier.1')).toBe(true);
    expect(isDressed('boston', 'layer.suburbs.gameday.start')).toBe(false);
    expect(isDressed(undefined, 'upgrade.waterfront.rack.tier.1')).toBe(false);
    expect(isDressed('home', 'toString')).toBe(false);
    expect(dressed('boston', 'label.nextBoat', 'Next boat')).toBe('Next order');
    expect(dressed('home', 'label.nextBoat', 'Next boat')).toBe('Next boat');
  });
  test('an unknown key says itself', () => {
    expect(t('no.such.key')).toBe('no.such.key');
  });
});

describe('the home tables', () => {
  test('no key is in two tables, so one merged lookup is the same words', () => {
    const tables = [CHAPTERS, ENDGAME, LAYER_COPY, MENU, SHIFTS, STARS, TUTORIAL, LINES];
    const keys = tables.flatMap((tb) => Object.keys(tb));
    expect(new Set(keys).size).toBe(keys.length);
    expect(Object.keys(HOME_COPY)).toHaveLength(keys.length);
  });
  test('every pack override replaces a key the home tables have or is an ask the home screens read through `dressed`', () => {
    for (const key of Object.keys(BOSTON_COPY)) expect(typeof BOSTON_COPY[key]).toBe('string');
    for (const key of ['upgrade.waterfront.rack.tier.1', 'layer.uptown.stars.banner', 'layer.industrial.jam.alert']) expect(key in BOSTON_COPY).toBe(true);
  });
  test('every line that names the founder names it as {founder}', () => {
    for (const [k, v] of Object.entries(LINES)) if (/founder/.test(k) || /\{founder\}/.test(v)) expect(v).not.toMatch(/Nonna/);
  });
  test('the generated tables say they are generated, by the command', () => {
    for (const f of ['endgame', 'layers', 'menu', 'shifts', 'stars']) {
      const head = fs.readFileSync(path.join(__dirname, '../copy/home', `${f}.ts`), 'utf8').split('\n')[0];
      expect(head).toMatch(/^\/\/ GENERATED by `npx tsx scripts\/gen-copy\.ts`/);
    }
  });
});

describe('a pack never imports content/copy (no cycle)', () => {
  test('no file under content/cities names it', () => {
    const walk = (d: string): string[] =>
      fs
        .readdirSync(d, { withFileTypes: true })
        .flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : /\.tsx?$/.test(e.name) ? [path.join(d, e.name)] : []));
    for (const f of walk(path.join(__dirname, '../cities'))) {
      if (f.includes('__tests__')) continue;
      expect(fs.readFileSync(f, 'utf8')).not.toMatch(/from '(\.\.\/)+copy(\/[^']*)?'/);
    }
  });
});
